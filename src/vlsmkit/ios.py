"""Render Cisco IOS configuration and parse it back.

:func:`render` turns a :class:`~vlsmkit.spec.Router` into a paste-ready
config script. :func:`parse` extracts the routing-relevant facts from any IOS
script (generated or hand written) so two configs can be compared
semantically, independent of ordering, comments and whitespace.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from ipaddress import IPv4Address, IPv4Interface, IPv4Network

from vlsmkit.spec import Router

__all__ = ["ParsedConfig", "parse", "parse_many", "render"]

HEADER = "! Generated by vlsmkit from network.toml. Do not edit by hand."


def render(router: Router) -> str:
    """Return the full configuration script for ``router``."""
    lines = [
        HEADER,
        "enable",
        "configure terminal",
        f"hostname {router.hostname}",
        "!",
    ]
    for iface in router.interfaces:
        lines += [
            f"interface {iface.name}",
            f" description {iface.description}",
            f" ip address {iface.address.ip} {iface.address.netmask}",
        ]
        if iface.dhcp_relay is not None:
            lines.append(f" ip helper-address {iface.dhcp_relay}")
        lines += [" no shutdown", " exit", "!"]

    for route in router.static_routes:
        lines.append(
            f"ip route {route.destination.network_address} "
            f"{route.destination.netmask} {route.next_hop}"
        )
    if router.static_routes:
        lines.append("!")

    if router.ospf is not None:
        ospf = router.ospf
        lines += [f"router ospf {ospf.process}", f" router-id {ospf.router_id}"]
        lines += [
            f" network {n.network_address} {n.hostmask} area {ospf.area}" for n in ospf.networks
        ]
        lines += [f" passive-interface {name}" for name in ospf.passive]
        lines += [f" redistribute {proto} subnets" for proto in ospf.redistribute]
        lines += [" exit", "!"]

    lines += ["end", "write memory", ""]
    return "\n".join(lines)


@dataclass
class ParsedConfig:
    """Routing-relevant state extracted from an IOS script."""

    hostname: str = ""
    interfaces: dict[str, IPv4Interface] = field(default_factory=dict)
    helpers: dict[str, IPv4Address] = field(default_factory=dict)
    static_routes: set[tuple[IPv4Network, IPv4Address]] = field(default_factory=set)
    ospf_networks: set[tuple[IPv4Network, int]] = field(default_factory=set)
    ospf_router_id: IPv4Address | None = None
    passive: set[str] = field(default_factory=set)
    redistribute: set[str] = field(default_factory=set)


_IP = r"(\d+\.\d+\.\d+\.\d+)"
_PATTERNS = {
    "hostname": re.compile(r"^hostname\s+(\S+)"),
    "interface": re.compile(r"^interface\s+(\S+)"),
    "address": re.compile(rf"^ip address\s+{_IP}\s+{_IP}"),
    "helper": re.compile(rf"^ip helper-address\s+{_IP}"),
    "route": re.compile(rf"^ip route\s+{_IP}\s+{_IP}\s+{_IP}"),
    "ospf": re.compile(r"^router ospf\s+\d+"),
    "network": re.compile(rf"^network\s+{_IP}\s+{_IP}\s+area\s+(\d+)"),
    "router_id": re.compile(rf"^router-id\s+{_IP}"),
    "passive": re.compile(r"^passive-interface\s+(\S+)"),
    "redistribute": re.compile(r"^redistribute\s+(\S+)"),
}


def _wildcard_to_network(address: str, wildcard: str) -> IPv4Network:
    mask = IPv4Address(int(IPv4Address(wildcard)) ^ 0xFFFFFFFF)
    return IPv4Network(f"{address}/{mask}")


def parse(text: str) -> ParsedConfig:
    """Parse one router's IOS script."""
    cfg = ParsedConfig()
    section: str | None = None  # current interface name, "ospf", or None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("!"):
            continue
        indented = raw.startswith(" ")
        if not indented:
            section = None
        if m := _PATTERNS["hostname"].match(line):
            cfg.hostname = m[1]
        elif m := _PATTERNS["interface"].match(line):
            section = m[1]
        elif _PATTERNS["ospf"].match(line):
            section = "ospf"
        elif m := _PATTERNS["route"].match(line):
            cfg.static_routes.add((IPv4Network(f"{m[1]}/{m[2]}"), IPv4Address(m[3])))
        elif section == "ospf":
            if m := _PATTERNS["network"].match(line):
                cfg.ospf_networks.add((_wildcard_to_network(m[1], m[2]), int(m[3])))
            elif m := _PATTERNS["router_id"].match(line):
                cfg.ospf_router_id = IPv4Address(m[1])
            elif m := _PATTERNS["passive"].match(line):
                cfg.passive.add(m[1])
            elif m := _PATTERNS["redistribute"].match(line):
                cfg.redistribute.add(m[1])
        elif section is not None:
            if m := _PATTERNS["address"].match(line):
                cfg.interfaces[section] = IPv4Interface(f"{m[1]}/{m[2]}")
            elif m := _PATTERNS["helper"].match(line):
                cfg.helpers[section] = IPv4Address(m[1])
    return cfg


def parse_many(text: str) -> dict[str, ParsedConfig]:
    """Parse a file holding several routers' scripts, split on ``hostname``."""
    chunks = re.split(r"(?m)^(?=hostname\s)", text)
    configs = [parse(chunk) for chunk in chunks if chunk.lstrip().startswith("hostname")]
    return {c.hostname: c for c in configs}
