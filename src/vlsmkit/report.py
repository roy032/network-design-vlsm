"""Human-readable reports: VLSM tree, Markdown tables and JSON."""

from __future__ import annotations

import json
from collections.abc import Iterable, Sequence
from ipaddress import IPv4Network
from typing import Any

from vlsmkit.allocator import Allocation
from vlsmkit.routing import build_routing_tables, reachability_matrix
from vlsmkit.spec import Network

__all__ = ["addressing_markdown", "plan_json", "plan_table", "vlsm_tree"]


def _covering(allocations: Sequence[Allocation]) -> IPv4Network:
    """Smallest block that contains every allocation."""
    block = allocations[0].network
    while not all(a.network.subnet_of(block) for a in allocations):
        block = block.supernet()
    return block


def vlsm_tree(allocations: Sequence[Allocation]) -> str:
    """Render the binary split tree that produces ``allocations``.

    Only blocks on the path to an allocation are expanded; untouched halves
    are shown once as free space, which keeps the tree short and correct.
    """
    if not allocations:
        return ""
    by_net = {a.network: a for a in allocations}
    root = _covering(allocations)
    lines: list[str] = []

    def label(block: IPv4Network) -> str:
        if block in by_net:
            a = by_net[block]
            return f"{block}  <- {a.name} ({a.hosts_required} hosts, {a.usable_hosts} usable)"
        if not any(a.network.overlaps(block) for a in allocations):
            return f"{block}  (free)"
        return str(block)

    def walk(block: IPv4Network, prefix: str, connector: str) -> None:
        lines.append(f"{prefix}{connector}{label(block)}")
        expandable = block not in by_net and any(a.network.subnet_of(block) for a in allocations)
        if not expandable:
            return
        if not connector:
            child_prefix = prefix
        else:
            child_prefix = prefix + ("    " if connector == "└── " else "│   ")
        low, high = block.subnets(prefixlen_diff=1)
        walk(low, child_prefix, "├── ")
        walk(high, child_prefix, "└── ")

    walk(root, "", "")
    return "\n".join(lines)


def _table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def plan_table(allocations: Sequence[Allocation]) -> str:
    """Markdown table of an allocation plan."""
    return _table(
        ["Subnet", "Hosts needed", "Usable", "Network", "Mask", "Usable range", "Broadcast"],
        (
            (
                a.name,
                a.hosts_required,
                a.usable_hosts,
                a.network,
                a.netmask,
                f"{a.first_host} - {a.last_host}",
                a.broadcast,
            )
            for a in allocations
        ),
    )


def plan_json(allocations: Sequence[Allocation]) -> str:
    data: list[dict[str, Any]] = [
        {
            "name": a.name,
            "hosts_required": a.hosts_required,
            "usable_hosts": a.usable_hosts,
            "network": str(a.network),
            "netmask": str(a.netmask),
            "wildcard": str(a.wildcard),
            "first_host": str(a.first_host),
            "last_host": str(a.last_host),
            "broadcast": str(a.broadcast),
        }
        for a in allocations
    ]
    return json.dumps(data, indent=2) + "\n"


def addressing_markdown(network: Network) -> str:
    """The complete generated design document for ``network``."""
    allocs = [Allocation(s.name, s.allocation.hosts_required, s.network) for s in network.subnets]
    used = sum(a.network.num_addresses for a in allocs)
    requested = sum(a.hosts_required for a in allocs)
    usable = sum(a.usable_hosts for a in allocs)
    root = _covering(allocs)

    sections = [
        f"# {network.name}: generated design",
        "> Generated by `vlsmkit build` from [`network.toml`](../../network.toml). "
        "Do not edit by hand; CI fails if this file is stale.",
        "## Summary",
        _table(
            ["Metric", "Value"],
            [
                ("Supernet", network.supernet),
                ("Allocated block", f"{root} ({used} of {root.num_addresses} addresses used)"),
                ("Hosts requested", requested),
                ("Usable addresses allocated", usable),
                ("Efficiency (requested / usable)", f"{requested / usable:.1%}"),
            ],
        ),
        "## Subnet plan (VLSM, largest first)",
        plan_table(sorted(allocs, key=lambda a: (a.prefixlen, a.network))),
        "## VLSM tree",
        "```text\n" + vlsm_tree(allocs) + "\n```",
        "## Router interfaces",
        _table(
            ["Router", "Interface", "Address", "Mask", "Subnet", "Description"],
            (
                (
                    r.hostname,
                    i.short_name,
                    i.address.ip,
                    i.address.netmask,
                    i.subnet.name,
                    i.description,
                )
                for r in network.routers
                for i in r.interfaces
            ),
        ),
        "## Static hosts",
        _table(
            ["Device", "Address", "Mask", "Gateway", "Subnet", "Role"],
            (
                (h.name, h.address, h.subnet.network.netmask, h.gateway, h.subnet.name, h.role)
                for h in network.hosts
            ),
        ),
    ]

    dns_server = next((h for h in network.hosts if "dns" in h.dns), None)
    pools = [s for s in network.subnets if s.dhcp is not None and s.dhcp_range is not None]
    if pools:
        sections += [
            "## DHCP pools",
            _table(
                ["Pool", "Network", "Gateway", "DNS", "Range", "Relay agents"],
                (
                    (
                        s.dhcp.name if s.dhcp else "",
                        s.network,
                        s.allocation.first_host,
                        dns_server.address if dns_server else "-",
                        f"{s.dhcp_range[0]} - {s.dhcp_range[1]}" if s.dhcp_range else "",
                        ", ".join(
                            f"{r.hostname} {i.short_name}"
                            for r in network.routers
                            for i in r.interfaces
                            if i.subnet.id == s.id and i.dhcp_relay is not None
                        ),
                    )
                    for s in pools
                ),
            ),
        ]

    records = [
        ("A", f"{name}.{network.domain}" if name != "@" else network.domain, h.address)
        for h in network.hosts
        for name in h.dns
    ]
    records += [("MX", network.domain, h.address) for h in network.hosts if h.mx]
    if records:
        sections += ["## DNS records", _table(["Type", "Name", "Value"], records)]

    tables = build_routing_tables(network)
    sections.append("## Simulated routing tables")
    for hostname, routes in tables.items():
        sections.append(f"**{hostname}**\n\n```text\n" + "\n".join(map(str, routes)) + "\n```")

    matrix = reachability_matrix(network)
    ids = [s.id for s in network.subnets]
    names = {s.id: s.name for s in network.subnets}
    rows = []
    for a in ids:
        row: list[object] = [f"**{names[a]}**"]
        for b in ids:
            if a == b:
                row.append("·")
            else:
                req, rep = matrix[(a, b)]
                row.append("✅" if req.ok and rep.ok else "❌")
        rows.append(row)
    failures = [
        f"- {names[a]} → {names[b]}: " + "; ".join(str(t) for t in (req, rep) if not t.ok)
        for (a, b), (req, rep) in matrix.items()
        if not (req.ok and rep.ok)
    ]
    lan_ids = {s.id for s in network.lans}
    lan_ok = all(
        req.ok and rep.ok for (a, b), (req, rep) in matrix.items() if a in lan_ids and b in lan_ids
    )
    sections += [
        "## Reachability (simulated round-trip ping between subnets)",
        "Rows are sources, columns destinations. Each cell traces both the "
        "echo request and the reply through the simulated routing tables.",
        _table(["From \\ To", *(names[i] for i in ids)], rows),
        f"**LAN to LAN reachability: {'PASS' if lan_ok else 'FAIL'}**",
    ]
    if failures:
        sections += ["### Unreachable pairs", "\n".join(failures)]
    return "\n\n".join(sections) + "\n"
